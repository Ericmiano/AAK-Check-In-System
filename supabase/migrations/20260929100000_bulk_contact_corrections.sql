update public.delegates d
set email = case
      when nullif(btrim(c.email), '') is null then d.email
      -- Some corrections collide with an existing OTHER delegate's email —
      -- always a duplicate-person situation (e.g. "Hellen" and "Hellen
      -- Ouko" as two separate records for the same attendee). Skip just
      -- the email in that case rather than failing the whole row; the
      -- organization/phone corrections below still apply.
      when exists (
        select 1 from public.delegates other
        where other.event_id = d.event_id
          and other.id <> d.id
          and other.email = lower(btrim(c.email))
      ) then d.email
      else lower(btrim(c.email))
    end,
    organization = coalesce(nullif(btrim(c.organization), ''), d.organization),
    phone = coalesce(nullif(btrim(c.phone), ''), d.phone)
from corrections c
where d.event_id = public.active_event_id()
  and public.normalize_name(d.full_name) = public.normalize_name(c.full_name);
